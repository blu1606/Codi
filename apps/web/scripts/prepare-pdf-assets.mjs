import { cpSync, mkdirSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
const require = createRequire(import.meta.url);
const root = dirname(require.resolve("pdfjs-dist/package.json"));
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const target = new URL(`../public/pdfjs/${version}/`, import.meta.url);
mkdirSync(target, { recursive: true });
cpSync(join(root, "build/pdf.worker.min.mjs"), new URL("pdf.worker.min.mjs", target));
for (const directory of ["cmaps", "standard_fonts", "wasm"]) cpSync(join(root, directory), new URL(directory, target), { recursive: true });
console.log(`Prepared local PDF.js ${version} assets`);
